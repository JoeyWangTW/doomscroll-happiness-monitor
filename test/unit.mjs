import { computeMood, sessionStats, dominantExpression, trendLabel } from '../src/shared/mood.js';
import { matchTracked, hostnameFromUrl, normalizeDomain } from '../src/shared/settings.js';
const assert = (c, m) => { if (!c) { console.error('FAIL', m); process.exitCode = 1; } else console.log('ok', m); };
assert(computeMood({ happy: 1 }) === 1, 'happy=1 -> +1');
assert(computeMood({ sad: 0.5, angry: 0.5 }) === -1, 'sad+angry -> -1');
assert(computeMood({ neutral: 1 }) === 0, 'neutral -> 0');
assert(dominantExpression({ neutral: 0.2, happy: 0.7, sad: 0.1 }) === 'happy', 'dominant');
const t0 = 1e12;
const frames = [];
for (let i = 0; i < 30; i++) frames.push({ ts: t0 + i * 3000, faceFound: true, mood: -0.5 + i / 30, expressions: { happy: i / 30 } });
frames.push({ ts: t0 + 99000, faceFound: false, mood: null });
const st = sessionStats(frames);
assert(st.n === 30 && st.total === 31, 'counts');
assert(st.label === 'improving' && st.delta > 0.5, 'trend improving ' + st.delta.toFixed(2));
assert(Math.abs(st.slopePerMin - (1 / 30) / 0.05) < 1e-6, 'slope per minute ' + st.slopePerMin);
assert(sessionStats([]).label === 'no data', 'empty');
assert(trendLabel(-0.2) === 'declining', 'declining');
const doms = ['youtube.com', 'x.com', 'Reddit.com'];
assert(matchTracked(hostnameFromUrl('https://www.youtube.com/watch?v=1'), doms) === 'youtube.com', 'youtube www');
assert(matchTracked(hostnameFromUrl('https://m.youtube.com/'), doms) === 'youtube.com', 'youtube subdomain');
assert(matchTracked(hostnameFromUrl('https://notx.com/'), doms) === null, 'no suffix false positive');
assert(matchTracked(hostnameFromUrl('https://old.reddit.com/r/a'), doms) === 'reddit.com', 'case-insensitive');
assert(matchTracked(hostnameFromUrl('chrome://extensions'), doms) === null, 'chrome url');
assert(normalizeDomain(' https://www.TikTok.com/foo ') === 'tiktok.com', 'normalize');
